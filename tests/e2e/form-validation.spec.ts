import { test, expect, type Page } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

const phrase = 'fictional browser vault unlock phrase';
async function enter(page: Page) {
  await page.goto('/');
  await page.locator('[name="login"]').fill('fictional-ui');
  await page.locator('[name="password"]').fill('fictional-login-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  const create = page.getByRole('heading', { name: '创建私人资料库' });
  await expect(create.or(page.getByRole('heading', { name: '打开你的资料库' }))).toBeVisible();
  if (await create.isVisible()) {
    await page.locator('[name="setupPassphrase"]').fill('short');
    await page.locator('[name="setupRepeated"]').fill('different');
    await page.locator('[name="setupRepeated"]').press('Enter');
    await expect(page.locator('#setup-form .field-error')).toHaveCount(2);
    await expect(page.locator('[name="setupPassphrase"]')).toBeFocused();
    await capture(page, 'desktop-setup-errors');
    await page.locator('[name="setupPassphrase"]').fill(phrase);
    await page.locator('[name="setupRepeated"]').fill(phrase);
    await page.getByRole('button', { name: '创建资料库', exact: true }).click();
    await expect(page.getByRole('heading', { name: '保存独立恢复秘密' })).toBeVisible();
    await page.getByRole('checkbox', { name: '我已安全保存，并理解丢失后的风险' }).check();
    await page.getByRole('button', { name: '进入知交', exact: true }).click();
  } else {
    await page.locator('[name="unlockSecret"]').fill('short');
    await page.getByRole('button', { name: '解锁资料库', exact: true }).click();
    await expect(page.locator('[name="unlockSecret"]')).toBeFocused();
    await expect(page.locator('#unlock-form .field-error')).toHaveCount(1);
    await page.locator('[name="unlockSecret"]').fill(phrase);
    await page.getByRole('button', { name: '解锁资料库', exact: true }).click();
  }
  await expect(page.getByRole('button', { name: '记一笔', exact: true }).first()).toBeVisible();
}
async function capture(page: Page, name: string) {
  // Only fictional non-secret states are captured; automatic traces/screenshots stay off.
  await mkdir('.local/form-check/screenshots', { recursive: true });
  await page.screenshot({ path: `.local/form-check/screenshots/${name}.png`, fullPage: true });
}

test('login: quiet initial state, Chinese inline errors, first focus and retained server errors', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  let loginRequests = 0;
  page.on('request', request => { if (request.url().endsWith('/api/auth/login')) loginRequests++; });
  await page.goto('/');
  await page.evaluate(() => { (window as Window & { invalidEvents: number }).invalidEvents = 0; document.addEventListener('invalid', () => { (window as Window & { invalidEvents: number }).invalidEvents++; }, true); });
  const form = page.locator('#login-form');
  await expect(form.locator('.field-error')).toHaveCount(0);
  await form.locator('[name="login"]').focus();
  await form.locator('[name="password"]').focus();
  await expect(form.getByText('请填写登录名。', { exact: true })).toBeVisible();
  await expect(form.locator('[name="password"]')).toBeFocused();
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(form.locator('[name="login"]')).toBeFocused();
  await expect(form.locator('.field-error')).toHaveCount(2);
  const description = await form.locator('[name="login"]').getAttribute('aria-describedby');
  expect(description).toBeTruthy();
  await expect(page.locator(`[id="${description}"]`)).toHaveText('请填写登录名。');
  expect(loginRequests).toBe(0);
  expect(await page.evaluate(() => (window as Window & { invalidEvents: number }).invalidEvents)).toBe(0);
  await capture(page, 'desktop-login-errors');
  await form.locator('[name="login"]').fill('fictional-ui');
  await form.locator('[name="password"]').fill('fictional-login-password');
  await expect(form.locator('.field-error')).toHaveCount(0);
  await page.route('**/api/auth/login', route => route.fulfill({ status: 429, json: { code: 'RATE_LIMIT' } }));
  await page.getByRole('button', { name: '登录', exact: true }).dblclick();
  await expect(page.getByRole('alert')).toHaveText('操作较频繁，请稍后再试。');
  expect(loginRequests).toBe(1);
});

