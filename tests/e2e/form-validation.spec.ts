  await enter(page);
  await page.getByRole('button', { name: '记一笔', exact: true }).first().click();
  const journal = page.getByRole('dialog', { name: '记一笔' });
  await journal.getByRole('button', { name: '添加', exact: true }).click();
  await journal.getByRole('button', { name: '保存这一笔', exact: true }).click();
  await expect(journal.locator('.field-error')).toHaveCount(4);
  await capture(page, 'mobile-journal-errors');
  const buttonBox = await journal.getByRole('button', { name: '保存这一笔', exact: true }).boundingBox();
  expect(buttonBox && buttonBox.y + buttonBox.height).toBeLessThanOrEqual(844);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 390, height: 520 });
  await journal.locator('[name="title"]').focus();
  const shortBox = await journal.getByRole('button', { name: '保存这一笔', exact: true }).boundingBox();
  expect(shortBox && shortBox.y + shortBox.height).toBeLessThanOrEqual(520);
  await page.setViewportSize({ width: 390, height: 844 });
  await journal.getByRole('button', { name: '已有印象', exact: true }).click();
  await expect(journal.locator('[name$=".content"]')).toHaveCount(0);
  await expect(journal.locator('[name$=".existing"]')).toBeVisible();
  await journal.getByRole('button', { name: '移除此条感受' }).click();
  await expect(journal.locator('.field-error')).toHaveCount(1);
  await journal.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: '设置', exact: true }).first().click();
  const rewrap = page.locator('#rewrap-form');
  await rewrap.getByRole('button', { name: '更新解锁口令' }).click();
